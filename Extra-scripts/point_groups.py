"""
Usage:
    python3 point_groups.py [--qe] [--target]

Examples VASP:
    python3 point_groups.py wfc_s2_k1_b430_r.vasp                              
    python3 point_groups.py wfc_s2_k1_b430_r.vasp wfc_s2_k1_b430_i.vasp       
    python3 point_groups.py wfc_s2_k1_b430_r.vasp --target D_2d
    python3 point_groups.py wfc_s2_k1_b431_r.vasp wfc_s2_k1_b432_r.vasp

Examples QE:    
    python3 point_groups.py --qe wfc_band430_dw.xsf 
    python3 point_groups.py --qe wfc_band430_dw.xsf --target D_2d
    python3 point_groups.py --qe wfc_band431_dw.xsf wfc_band432_dw.xsf    

Point group for use is read from correction.json

Identifies the irreducible representation to which a Kohn-Sham orbital
belongs, from either:
  - VASP in VESTA format (.vasp), such as produced by ks-orbital.py /
    wav.save2vesta() -- this is the DEFAULT, or
  - Quantum ESPRESSO in XCrySDen structure format (.xsf), i.e. a file
    that embeds a 'BEGIN_BLOCK_DATAGRID_3D' volumetric section for a
    single band (e.g. as produced by pp.x), pass --qe to select this.

Method:
  1. The real-space FFT grid (nx,ny,nz) is parsed from the input file
     (.vasp by default, or .xsf with --qe; see read_vesta_grid /
     read_xsf_grid). For .xsf, XCrySDen's convention for periodic data
     repeats the first grid point as an extra last point along each
     axis (so a genuine nx x ny x nz FFT grid is stored as (nx+1) x
     (ny+1) x (nz+1) values); that redundant last point is dropped on
     read to recover the intrinsic FFT grid, exactly as QE itself uses
     it.
  2. The 48 operations of O_h (the full cubic holohedry: all signed
     permutations of x,y,z) are generated as the universal PARENT group,
     valid whenever the cell axes coincide with the cubic cell axes,
     as for a defect in a zincblende/rocksalt/diamond-type lattice with
     the cell aligned to x,y,z as in the POSCAR. Every point group that
     can occur as the local symmetry of such a defect (T_d, T, O, O_h,
     D_2d, D_4h, C_3v, D_3d, C_2v, S_4, C_4v, ..., any of the 32
     crystallographic point groups compatible with a cubic cell) is a
     subgroup of O_h, so this single parent group replaces the old
     T_d-only (24-operation) parent.
  3. GIVEN ANY point-group name recognized by point_groups_lib.py (read from
     correction.json, or given explicitly with --target), the script
     searches for that group as a concrete subgroup of the 48 O_h
     operations: it enumerates subgroups generated by pairs of O_h
     operations, keeps the ones whose order matches, computes their
     TRUE conjugacy classes by matrix multiplication (no per-group
     hand-written logic), and matches those classes against the class
     list declared for that group in point_groups_lib.py. Each valid match
     is one physical "orientation" (e.g. one of the four <111> axes for
     C_3v), exactly what the old axis-search functions did by hand
     for T_d/D_2d/C_3v specifically, done here once, generically, for
     any group in the catalog.
  4. For each orientation found, phi(R^-1 (r-c)+c) is interpolated on
     the grid (periodic boundary conditions, cubic spline). For n input
     .vasp files the trace of the n x n normalized overlap matrix
     Tr[S(R)], S_ij(R) = <phi_i|R phi_j> / sqrt(<phi_i|phi_i><phi_j|phi_j>),
     is used as the character chi(R) -- this is the correct
     generalization for ANY degeneracy order n: giving 1 file analyzes
     the non-degenerate case, 2 files the doubly-degenerate case, 3
     files the triply-degenerate case, and so on for as many bands as
     are given (for n=1 the formula reduces exactly to the familiar
     chi(R) = <phi|R phi>/<phi|phi>). The characters are averaged per
     class and reduced into irreps with PointGroup.reduce_representation,
     which only ever uses the irreps that belong to that one target
     group (never irreps from another group). Because chi(E) = n is
     fixed by construction, the reduction is forced to sum to n, either
     as a single genuine irrep of dimension n, or as an accidental
     degeneracy of several smaller irreps, both cases are reported
     explicitly. The best-fitting orientation (integer-closest
     reduction) is reported.
  5. Groups that cannot occur in a cubic cell (e.g. C_5v, D_5, or the
     icosahedral/continuous groups) are still looked up in
     point_groups_lib.py exactly like any other group; the generic subgroup
     search then correctly reports that no realization exists inside
     O_h, rather than silently doing something wrong.

Defect location and point-group information:
  All of this is always read from a file named correction.json: in the working 
  directory by default, or in the PARENT of the working directory with --qe. 
  'defect_frac_coords' is used as the symmetry center, and the 'point group' block
  (perfect/defect, Hermann-Mauguin/Schoenflies) is printed for reference
  and used to pick the target group. --target lets you force the
  analysis for any point group in point_groups_lib.py's catalog directly
  (overrides the label read from correction.json).

Number of BANDS given = degeneracy order analyzed:
  1 band  -> non-degenerate case (n=1)
  2 bands -> doubly-degenerate case (n=2)
  3 bands -> triply-degenerate case (n=3)
  ... and so on for any n, as long as the target point group actually
  has a way to realize it (a genuine n-D irrep, or an accidental sum
  of smaller irreps), see describe_multiplet().

Real and imaginary parts (optional, per band):
  Each band may be given as a single real-valued file, or
  as a REAL + IMAGINARY pair to build a complex orbital phi = real +
  i*imag. Pairing is automatic, based on the same '..._r.EXT' /
  '..._i.EXT' naming already used for the real-only files (EXT =
  'vasp' by default, 'xsf' with --qe): two files sharing everything up
  to a trailing '_r'/'_i' before the extension (e.g.
  wfc_s2_k1_b430_r.vasp and wfc_s2_k1_b430_i.vasp, sharing base
  'wfc_s2_k1_b430') are combined into ONE complex band. A file given
  on its own -- only the '_r' one, only the '_i' one, or a filename
  that doesn't follow the '_r'/'_i' convention at all -- is treated as
  a single real-valued band, exactly as before, so old-style
  invocations are unaffected. Complex and real-valued bands can be
  freely mixed within one run (see read_multi/pair_real_imag_files).
  Overlaps <i|R j> then use the proper complex inner product (conjugate
  the bra); the resulting per-class characters are averaged and their
  real part taken (a non-negligible imaginary part triggers a warning,
  since the characters of these point groups are real).
"""

